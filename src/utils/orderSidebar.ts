import type { SidebarEntry } from '@astrojs/starlight/utils/routing/types';
import { getCollection } from 'astro:content';

const localePrefix = /^\/(en|de|es|fr|ja|ko|pt|vi|th|ru|zh-tw)(?=\/)/;
const withSlash = (path: string) => (path.endsWith('/') ? path : `${path}/`);
const normalize = (href: string) => withSlash(href.replace(localePrefix, ''));

let orderMap: Promise<Map<string, number>> | undefined;

/** Sidebar order keyed by root-locale path; a directory takes its index page's order. */
function getOrderMap() {
	orderMap ??= getCollection('docs').then((docs) => {
		const map = new Map<string, number>();
		for (const { id, data } of docs) {
			if (localePrefix.test(`/${id}`) || data.sidebar?.order === undefined) continue;
			map.set(withSlash(`/${id.replace(/(^|\/)index$/, '')}`), data.sidebar.order);
		}
		return map;
	});
	return orderMap;
}

function links(entries: SidebarEntry[]): string[] {
	return entries.flatMap((entry) => (entry.type === 'link' ? [normalize(entry.href)] : links(entry.entries)));
}

function groupDir(entries: SidebarEntry[]): string | undefined {
	const hrefs = links(entries);
	if (hrefs.length === 0) return undefined;
	let prefix = hrefs[0];
	for (const href of hrefs) while (!href.startsWith(prefix)) prefix = prefix.replace(/[^/]+\/$/, '');
	return prefix;
}

/**
 * Starlight weights an autogenerated directory by the lowest order of any page inside it,
 * so a child page with `order: 1` drags its whole group to the top. Re-sort groups by
 * their own index page's `sidebar.order` instead; ties keep Starlight's order.
 */
export async function orderSidebarGroups(entries: SidebarEntry[]): Promise<SidebarEntry[]> {
	const map = await getOrderMap();
	const weigh = (entry: SidebarEntry, dir: string | undefined) => {
		const key = entry.type === 'link' ? normalize(entry.href) : groupDir(entry.entries);
		// A group's own overview page stays first; its order value ranks the group, not the page.
		if (key === dir) return -Infinity;
		return (key && map.get(key)) ?? Number.MAX_VALUE;
	};
	const sort = (list: SidebarEntry[]): SidebarEntry[] => {
		const dir = groupDir(list);
		return list
			.map((entry) => (entry.type === 'group' ? { ...entry, entries: sort(entry.entries) } : entry))
			.map((entry, index) => ({ entry, index, weight: weigh(entry, dir) }))
			.sort((a, b) => a.weight - b.weight || a.index - b.index)
			.map(({ entry }) => entry);
	};
	return sort(entries);
}
